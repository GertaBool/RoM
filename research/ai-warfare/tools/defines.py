#!/usr/bin/env python3
"""Every define in GlobalDefines.xml and GlobalDefinesAlt.xml with its value, the comment
above it, and where it is read (string-literal uses in the DLL, GC.getX() accessors,
Python). The game's final value is the last file's (SetGlobalDefines order).
usage: defines.py <Assets dir> <out.md>"""
import collections, os, re, sys
A, OUT = sys.argv[1], sys.argv[2]
dll = os.path.join(A, 'CvGameCoreDLL')
src = ''.join(open(os.path.join(dll, f), encoding='latin-1').read() for f in os.listdir(dll) if f.endswith(('.cpp', '.h')))
lit = collections.Counter(re.findall(r'"([A-Z0-9_]+)"', src))
acc = collections.Counter(m.upper() for m in re.findall(r'GC\.get([A-Za-z][A-Za-z0-9_]+)\(\)', src))
py = collections.Counter()
for p, _, fs in os.walk(os.path.join(A, 'Python')):
    for f in fs:
        if f.endswith('.py'):
            py.update(re.findall(r'"([A-Z0-9_]+)"', open(os.path.join(p, f), encoding='latin-1').read()))
out = open(OUT, 'w')
out.write('# GlobalDefines.xml and GlobalDefinesAlt.xml\n\nGenerated by [tools/defines.py](tools/defines.py). "DLL" counts string-literal reads plus `GC.getX()` accessors; "Py" counts Python reads. A define read by neither is inert.\n')
for name in ('GlobalDefines.xml', 'GlobalDefinesAlt.xml'):
    text = open(os.path.join(A, 'XML', name), encoding='latin-1').read()
    out.write('\n## %s\n\n| Define | Value | DLL | Py | Comment |\n|---|---|---|---|---|\n' % name)
    comment = ''
    for m in re.finditer(r'<!--(.*?)-->|<Define>(.*?)</Define>', text, re.S):
        if m.group(1) is not None:
            c = ' '.join(m.group(1).split())
            comment = c if len(c) < 240 else ''
            continue
        b = m.group(2)
        n = re.search(r'<DefineName>\s*([^<\s]*)', b).group(1)
        v = re.search(r'<(iDefineIntVal|fDefineFloatVal|DefineTextVal)>([^<]*)', b)
        out.write('| %s | %s | %d | %d | %s |\n' % (n, v.group(2).strip() if v else '', lit[n] + acc[n], py[n], comment.replace('|', '/')))
        comment = ''
