#!/usr/bin/env python3
"""Generate HarnessRoMTables.h from Rise of Mankind's Python.

usage: gen_rom_tables.py <Assets/Python> <out.h>

The building upgrade lines (RoMGameUtils.py) become (upgrade, replaced) pairs
in the order the Python expands them; zCivics.py's addBuildingPre calls become
(building, civic) pairs. A missing file gives empty tables and a warning, so
older trees still build.
"""
import ast
import os
import re
import sys


def list_literal(text, name):
    start = text.index('self.%s = [' % name)
    i = text.index('[', start)
    depth = 0
    for j in range(i, len(text)):
        if text[j] == '[':
            depth += 1
        elif text[j] == ']':
            depth -= 1
            if depth == 0:
                return ast.literal_eval(text[i:j + 1])
    raise ValueError('unterminated list ' + name)


def upgrade_pairs(py_dir):
    path = os.path.join(py_dir, 'RoMGameUtils.py')
    try:
        text = open(path, encoding='latin-1').read()
        upgrades = list_literal(text, 'asBuildingUpgradeLine_Upgrade_Name')
        replaced = list_literal(text, 'asBuildingUpgradeLine_Obsolete_Name')
    except (OSError, ValueError) as e:
        sys.stderr.write('gen_rom_tables: no upgrade lines (%s)\n' % e)
        return []
    if len(upgrades) != len(replaced):
        raise SystemExit('gen_rom_tables: %d upgrade lines but %d replaced lists' % (len(upgrades), len(replaced)))
    return [(u, o) for ups, olds in zip(upgrades, replaced) for u in ups for o in olds]


def building_civics(py_dir):
    path = os.path.join(py_dir, 'zCivics.py')
    try:
        text = open(path, encoding='latin-1').read()
    except OSError as e:
        sys.stderr.write('gen_rom_tables: no zCivics prerequisites (%s)\n' % e)
        return []
    return re.findall(r'^\s*self\.addBuildingPre\("(\w+)",\s*"(\w+)"\)', text, re.M)


def table(name, pairs):
    rows = ''.join('\t{ "%s", "%s" },\n' % p for p in pairs)
    return 'static const char* const %s[][2] = {\n%s\t{ NULL, NULL }\n};\n' % (name, rows)


def main():
    py_dir, out = sys.argv[1], sys.argv[2]
    pairs = upgrade_pairs(py_dir)
    civics = building_civics(py_dir)
    with open(out, 'w') as f:
        f.write('// Generated by toolchain/harness/gen_rom_tables.py from Assets/Python; do not edit.\n')
        f.write(table('g_aszRoMUpgradePairs', pairs))
        f.write(table('g_aszRoMBuildingCivic', civics))
    print('gen_rom_tables: %d upgrade pairs, %d building civic prerequisites' % (len(pairs), len(civics)))


if __name__ == '__main__':
    main()
