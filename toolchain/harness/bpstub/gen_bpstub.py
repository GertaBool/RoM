#!/usr/bin/env python3
"""Generate an inert boost_python-vc71-mt-1_32.dll for headless runs.

Each import of CvGameCoreDLL.dll gets an implementation with the right calling
convention and stack cleanup, chosen from its demangled signature. Python is
reported uninitialized, so these only have to keep the few conversions the DLL
performs unconditionally (makePythonObject for event arguments) well-formed.
"""
import subprocess, sys

names = [l.strip() for l in open(sys.argv[1]) if l.strip().startswith('?')]
pairs = []
for n in names:
    out = subprocess.run(['llvm-undname', n], capture_output=True, text=True).stdout
    dl = [l for l in out.split('\n') if l.strip() and not l.startswith('?')]
    pairs.append((n, dl[0] if dl else n))

# behaviour by demangled signature substring: (kind, stack bytes)
#   ctor_null: this->m_p = NULL, return this     ctor_inert: this->m_p = inert
#   ctor_arg:  this->m_p = first arg             copy: this->m_p = (*arg)->m_p
#   ctor_ptr:  this->m_p = a "ptr" object holding the first arg (the C++ object being wrapped,
#              e.g. the CyCity* of makePythonObject), so the harness can evaluate callbacks
#   this_get:  return this->m_p                   ret_this0 / ret0 / ret_inert / ret_arg0 / ret_reg / ret_alloc
rules = [
    ('handle<struct _object>::handle<struct _object>(void)', 'ctor_null', 0, True),
    ('handle<struct _object>::handle<struct _object>(class boost::python::handle<struct _object> const &)', 'copy', 4, True),
    ('handle<struct _object>::get(void)', 'this_get', 0, True),
    ('handle<struct _object>::~handle', 'ret0', 0, True),
    ('list_base::list_base(struct boost::python::detail::borrowed_reference_t *)', 'ctor_arg', 4, True),
    ('list_base::~list_base', 'ret0', 0, True),
    ('tuple_base::tuple_base(struct boost::python::detail::borrowed_reference_t *)', 'ctor_arg', 4, True),
    ('tuple_base::tuple_base(struct boost::python::detail::new_reference_t *)', 'ctor_arg', 4, True),
    ('tuple_base::tuple_base(void)', 'ctor_inert', 0, True),
    ('tuple_base::tuple_base(struct boost::python::detail::tuple_base const &)', 'copy', 4, True),
    ('tuple_base::~tuple_base', 'ret0', 0, True),
    ('class_base::add_property', 'ret0', 12, True),
    ('enum_base::enum_base(', 'ctor_inert', 20, True),
    ('enum_base::add_value', 'ret0', 8, True),
    ('enum_base::~enum_base', 'ret0', 0, True),
    ('registration::to_python(', 'ret_inert', 4, True),
    ('class_base::class_base(', 'ctor_inert', 16, True),
    ('class_base::set_instance_size', 'ret0', 4, True),
    ('class_base::~class_base', 'ret0', 0, True),
    ('shared_ptr_deleter::shared_ptr_deleter(class boost::python::handle', 'ctor_arg', 4, True),
    ('shared_ptr_deleter::shared_ptr_deleter(struct boost::python::converter::shared_ptr_deleter const &)', 'copy', 4, True),
    ('shared_ptr_deleter::operator()', 'ret0', 4, True),
    ('shared_ptr_deleter::~shared_ptr_deleter', 'ret0', 0, True),
    ('py_function_impl_base::~py_function_impl_base', 'ret0', 0, True),
    ('py_function_impl_base::max_arity', 'ret0', 0, True),
    ('instance_holder::install(', 'ret0', 4, True),
    ('instance_holder::instance_holder(void)', 'ret_this0', 0, True),
    ('instance_holder::~instance_holder', 'ret0', 0, True),
    ('registration::get_class_object', 'ret0', 0, True),
    ('arg_to_python_base::arg_to_python_base(', 'ctor_ptr', 8, True),
    # cdecl
    ('api::setattr(', 'ret0', 0, False),
    ('objects::add_cast(', 'ret0', 0, False),
    ('objects::function_object(', 'sret_inert', 0, False),
    ('do_return_to_python(', 'ret_inert', 0, False),
    ('scope_setattr_doc(', 'ret0', 0, False),
    ('enum_base::to_python(', 'ret_inert', 0, False),
    ('api::operator+=(', 'ret_arg0', 0, False),
    ('registry::query(', 'ret_reg', 0, False),
    ('find_dynamic_type(', 'ret_arg0', 0, False),
    ('rvalue_from_python_stage1(', 'ret0_64', 0, False),
    ('registry::insert(', 'ret0', 0, False),
    ('add_to_namespace(', 'ret0', 0, False),
    ('register_dynamic_id_aux(', 'ret0', 0, False),
    ('instance_holder::allocate(', 'ret_alloc', 0, False),
    ('instance_holder::deallocate(', 'ret0', 0, False),
    ('find_static_type(', 'ret_arg0', 0, False),
    ('throw_error_already_set(', 'die', 0, False),
    ('get_lvalue_from_python(', 'ret0', 0, False),
    ('registry::lookup(', 'ret_reg', 0, False),
]

c = ['/* Generated by gen_bpstub.py. */',
     '#include <stdio.h>', '#include <stdlib.h>',
     'typedef struct { int r; void* t; } Obj;',
     'static void inert_dealloc(void* o) { (void)o; }',
     'static struct { int r; void* t; int s; const char* n; int b, i; void (*d)(void*); char pad[400]; } inert_type = { 1 << 30, 0, 0, "inert", 0, 0, inert_dealloc };',
     'static Obj inert_obj = { 1 << 30, &inert_type };',
     'static char dummy_registration[256];',
     'typedef struct { int r; void* t; void* p; } PtrObj;',
     'static struct { int r; void* t; int s; const char* n; int b, i; void (*d)(void*); char pad[400]; } ptr_type = { 1 << 30, 0, 0, "ptr", 0, 0, inert_dealloc };',
     '/* Arguments only live for the duration of a callback, so a ring of objects suffices. */',
     'static PtrObj ptr_pool[4096]; static unsigned ptr_next;',
     'static void* __cdecl make_ptr(void* p) { PtrObj* o = &ptr_pool[ptr_next++ & 4095]; o->r = 1 << 30; o->t = &ptr_type; o->p = p; return o; }',
     'void* bp_current_scope = 0;',
     'static void die(const char* n) { fprintf(stderr, "boost_python stub called: %s\\n", n); fflush(stderr); abort(); }',
     ]
defs = ['LIBRARY "boost_python-vc71-mt-1_32"', 'EXPORTS']
for idx, (mangled, d) in enumerate(pairs):
    if mangled.startswith('?current_scope@'):
        defs.append('    "%s"=bp_current_scope DATA' % mangled)
        continue
    rule = next((r for r in rules if r[0] in d), None)
    if rule is None:
        sys.exit('no rule for: ' + d)
    _, kind, pop, this = rule
    fn = 'bp_%d' % idx
    ret = 'ret %d' % pop if pop else 'ret'
    body = {
        'ctor_null': 'mov dword ptr [ecx], 0\n\t\tmov eax, ecx',
        'ctor_inert': 'lea eax, inert_obj\n\t\tmov dword ptr [ecx], eax\n\t\tmov eax, ecx',
        'ctor_arg': 'mov eax, [esp+4]\n\t\tmov dword ptr [ecx], eax\n\t\tmov eax, ecx',
        'ctor_ptr': 'push ecx\n\t\tpush dword ptr [esp+8]\n\t\tcall make_ptr\n\t\tadd esp, 4\n\t\tpop ecx\n\t\tmov dword ptr [ecx], eax\n\t\tmov eax, ecx',
        'copy': 'mov eax, [esp+4]\n\t\tmov eax, [eax]\n\t\tmov dword ptr [ecx], eax\n\t\tmov eax, ecx',
        'this_get': 'mov eax, [ecx]',
        'ret_this0': 'mov eax, ecx',
        'ret0': 'xor eax, eax',
        'ret0_64': 'xor eax, eax\n\t\txor edx, edx',
        'ret_inert': 'lea eax, inert_obj',
        'ret_arg0': 'mov eax, [esp+4]',
        'ret_reg': 'lea eax, dummy_registration',
        'sret_inert': 'mov eax, [esp+4]\n\t\tlea ecx, inert_obj\n\t\tmov dword ptr [eax], ecx',
    }.get(kind)
    if kind == 'ret_alloc':
        c.append('static void* %s_impl(void) { return calloc(1, 4096); }' % fn)
        body = 'jmp %s_impl' % fn
        ret = None
    if kind == 'die':
        c.append('static void %s_impl(void) { die("%s"); }' % (fn, d.replace('"', "'")))
        body = 'jmp %s_impl' % fn
        ret = None
    c.append('/* %s */' % d)
    c.append('__declspec(naked) void %s(void)\n{\n\t__asm {\n\t\t%s%s\n\t}\n}' % (fn, body, ('\n\t\t' + ret) if ret else ''))
    defs.append('    "%s"=%s' % (mangled, fn))
open(sys.argv[2], 'w').write('\n'.join(c) + '\n')
open(sys.argv[3], 'w').write('\n'.join(defs) + '\n')
print(len(pairs), 'exports')
