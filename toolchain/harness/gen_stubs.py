#!/usr/bin/env python3
"""Generate default implementations of the engine interfaces the DLL calls.

Every pure virtual method of the SDK's CvDLL*IFaceBase classes gets a body that
returns a neutral value. Hand-written subclasses in engine.cpp override the
methods that matter for simulation (path finding, XML, text, logging, memory).
"""
import re, sys, glob, os

SDK = sys.argv[1]
OUT = sys.argv[2]

def default_body(ret):
    r = ret.strip()
    if r == 'void':
        return '{}'
    if r.endswith('*'):
        return '{ return NULL; }'
    if r == 'bool':
        return '{ return false; }'
    if r in ('CvString', 'CvWString'):
        return '{ return %s(); }' % r
    if r in ('int', 'uint', 'unsigned int', 'float', 'byte', 'unsigned char', 'long', 'short', 'char'):
        return '{ return (%s)0; }' % r
    if r.endswith('Types') or r in ('InterfaceVisibility', 'LoadType'):
        # Engine enums: NO_ value is -1 for game enums; 0 is a safe neutral.
        return '{ return (%s)0; }' % r
    raise SystemExit('unhandled return type %r' % r)

out = ['// Generated by gen_stubs.py from the SDK interface headers. Do not edit.',
       '#pragma once']
for h in sorted(glob.glob(os.path.join(SDK, 'CvDLL*IFaceBase.h'))):
    out.append('#include "%s"' % os.path.basename(h))
classes = []
for path in sorted(glob.glob(os.path.join(SDK, 'CvDLL*IFaceBase.h'))):
    txt = open(path, errors='replace').read()
    txt = re.sub(r'//[^\n]*', '', txt)
    txt = re.sub(r'/\*.*?\*/', '', txt, flags=re.S)
    for cm in re.finditer(r'class\s+(CvDLL\w+IFaceBase)\s*(?::[^{]*)?\{(.*?)\n\};', txt, re.S):
        name, body = cm.group(1), cm.group(2)
        methods = []
        for m in re.finditer(r'virtual\s+([^;{]*?)\s*=\s*0\s*;', body, re.S):
            decl = ' '.join(m.group(1).split())
            mm = re.match(r'(.*?)\b(\w+)\s*\((.*)\)\s*(const)?$', decl)
            ret, fn, args, const = mm.group(1), mm.group(2), mm.group(3), mm.group(4) or ''
            if fn == 'getText' and '...' in args:
                # Variadic: forwarded by the hand-written class.
                methods.append('\tvirtual %s %s(%s) %s { return szIDTag; }' % (ret, fn, args, const))
                continue
            methods.append('\tvirtual %s %s(%s) %s %s' % (ret, fn, args, const, default_body(ret)))
        if not methods:
            continue
        classes.append(name)
        out.append('class S_%s : public %s\n{\npublic:' % (name, name))
        out.extend(methods)
        out.append('};\n')
open(OUT, 'w').write('\n'.join(out) + '\n')
print('classes:', ', '.join(classes))
