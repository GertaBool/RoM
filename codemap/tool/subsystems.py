#!/usr/bin/env python3
"""Group the AI classes' state into subsystems by who writes it, and write codemap/subsystems.md.

usage: subsystems.py [codemap dir]
Reads map/state.tsv (state.py). The members are those of the AI classes (CLASSES). Two members belong to the
same subsystem when one function writes both, directly, outside the lifecycle functions (constructors,
destructors, reset, init, uninit, read, write), which write every member and would join them all. A subsystem
is a connected group under that rule. Every member is listed, with every function that writes it and every
function that reads it (directly, or through an accessor, named after 'via'). Groups are ordered by the number
of readers outside the group's writers, largest first; nothing is left out. The grouping is mechanical: it
says which state moves together, not what the state means. Names for groups are not given.
"""
import collections, csv, os, re, sys

CLASSES = {'CvPlayerAI', 'CvCityAI', 'CvTeamAI', 'CvUnitAI', 'CvGameAI', 'CvSelectionGroupAI'}
LIFE = re.compile(r'::(~?\w+AI|read|write|reset|AI_reset|init|uninit|AI_init|AI_uninit)\(')


def main():
    cm = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    rows = list(csv.DictReader(open(os.path.join(cm, 'map', 'state.tsv'), encoding='utf-8'), delimiter='\t',
                               quoting=csv.QUOTE_NONE))
    rows = [r for r in rows if r['class'] in CLASSES]
    par = {}

    def find(x):
        while par.setdefault(x, x) != x:
            par[x] = par[par[x]]; x = par[x]
        return x
    members = sorted({(r['class'], r['member']) for r in rows})
    for m in members: find(('m',) + m)
    for r in rows:
        if r['access'] == 'write' and r['how'] == 'direct' and not LIFE.search(r['name']):
            par[find(('m', r['class'], r['member']))] = find(('f', r['function']))
    groups = collections.defaultdict(list)
    for m in members: groups[find(('m',) + m)].append(m)
    acc = collections.defaultdict(lambda: collections.defaultdict(list))
    for r in rows: acc[(r['class'], r['member'])][r['access']].append(r)

    def outside(g):
        w = {r['function'] for m in g for r in acc[m]['write']}
        return len({r['function'] for m in g for r in acc[m]['read']} - w)
    order = sorted(groups.values(), key=lambda g: (-outside(g), g))

    def show(r):
        return f"`{r['name']}`" + (f" via `{r['via_name']}`" if r['how'] == 'accessor' else '')
    with open(os.path.join(cm, 'map', 'state.tsv'), encoding='utf-8') as f:
        allnames = {l.split('\t')[0]: l.split('\t')[1] for l in f}
    for r in rows: r['via_name'] = allnames.get(r['via'], r['via'])

    L = ['# Subsystems of the AI, by the state they write',
         '',
         'Generated by `tool/subsystems.py` from `map/state.tsv`. Do not edit by hand.',
         '',
         'Two members are in the same group when one function writes both, outside the lifecycle functions. '
         'The groups say which state moves together, not what it means. Lists are complete.',
         '',
         f'{len(members)} members of {", ".join(sorted(CLASSES))}; {len(order)} groups, '
         f'{sum(1 for g in order if len(g) == 1)} of them a single member.',
         '',
         '| group | members | writers (outside the lifecycle) | readers outside its writers |',
         '|---|---|---|---|']
    for k, g in enumerate(order, 1):
        w = sorted({r['name'] for m in g for r in acc[m]['write'] if not LIFE.search(r['name'])})
        L.append(f'| [{k}](#group-{k}) | ' + ', '.join(f'`{c}::{m}`' for c, m in g) + f' | {len(w)} | {outside(g)} |')
    for k, g in enumerate(order, 1):
        L += ['', f'## Group {k}', '']
        for m in g:
            ws, rs = acc[m]['write'], acc[m]['read']
            L.append(f'### `{m[0]}::{m[1]}`')
            L.append('')
            L.append(f'- writes ({len(ws)}): ' + (', '.join(show(r) for r in sorted(ws, key=lambda r: r['name'])) or 'none'))
            L.append(f'- reads ({len(rs)}): ' + (', '.join(show(r) for r in sorted(rs, key=lambda r: r['name'])) or 'none'))
            L.append('')
    with open(os.path.join(cm, 'subsystems.md'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(L) + '\n')
    print(f'{len(members)} members, {len(order)} groups', file=sys.stderr)


if __name__ == '__main__':
    main()
